'use client'
import Link from 'next/link'
import { useState, useTransition } from 'react'
import { AuthShell } from '~/components/ui'
import { beginSetup, confirmSetup } from './actions'

export function SetupFlow({ token, email }: { token: string; email: string }) {
  const [step, setStep] = useState<'password' | 'authenticator' | 'codes'>('password')
  const [pw, setPw] = useState(''); const [pw2, setPw2] = useState('')
  const [secret, setSecret] = useState(''); const [qr, setQr] = useState('')
  const [code, setCode] = useState(''); const [codes, setCodes] = useState<string[]>([])
  const [saved, setSaved] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [pending, start] = useTransition()

  if (step === 'password') return (
    <AuthShell title="Set up your account" hint="Use a password you do not use anywhere else. A password manager is best.">
      <p className="text-sm text-ink-2">Account: <b className="text-ink">{email}</b></p>
      <form className="space-y-4" onSubmit={(e) => {
        e.preventDefault(); setError(null)
        if (pw !== pw2) return setError('The passwords do not match.')
        start(async () => { const r = await beginSetup(token, pw); if ('error' in r) return setError(r.error); setSecret(r.secret); setQr(r.qrSvg); setStep('authenticator') })
      }}>
        <label className="block text-sm font-semibold">Password (12+ characters)
          <input type="password" autoComplete="new-password" required minLength={12} className="input mt-2 font-normal" value={pw} onChange={(e) => setPw(e.target.value)} /></label>
        <label className="block text-sm font-semibold">Repeat password
          <input type="password" autoComplete="new-password" required minLength={12} className="input mt-2 font-normal" value={pw2} onChange={(e) => setPw2(e.target.value)} /></label>
        {error && <p role="alert" className="text-sm text-danger">{error}</p>}
        <button className="btn w-full" disabled={pending}>{pending ? 'Saving…' : 'Continue'}</button>
      </form>
    </AuthShell>
  )

  if (step === 'authenticator') return (
    <AuthShell title="Add an authenticator" hint="Works with any authenticator app (1Password, Google Authenticator, Authy, Microsoft Authenticator).">
      <p className="text-sm text-ink-2">Scan this code with your app, then enter the 6-digit code it shows.</p>
      {/* SVG generated by our own server from the otpauth URI */}
      <div role="img" aria-label="QR code for your authenticator app" className="mx-auto w-48 rounded-lg bg-white p-2" dangerouslySetInnerHTML={{ __html: qr }} />
      <details className="text-sm"><summary className="cursor-pointer text-ink-2">Can&apos;t scan? Enter the key manually</summary>
        <code className="mt-2 block break-all rounded-lg bg-subtle p-3 font-mono text-xs">{secret}</code></details>
      <form className="space-y-4" onSubmit={(e) => {
        e.preventDefault(); setError(null)
        start(async () => { const r = await confirmSetup(token, code); if ('error' in r) return setError(r.error); setCodes(r.backupCodes); setStep('codes') })
      }}>
        <input inputMode="numeric" autoComplete="one-time-code" maxLength={6} required placeholder="000000" aria-label="6-digit code" className="input h-12 font-mono text-lg tracking-widest" value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} />
        {error && <p role="alert" className="text-sm text-danger">{error}</p>}
        <button className="btn w-full" disabled={pending || code.length !== 6}>{pending ? 'Checking…' : 'Verify and finish'}</button>
      </form>
    </AuthShell>
  )

  return (
    <AuthShell title="Save your backup codes" hint="These are shown once. They are the only way in if you lose your phone.">
      <p className="text-sm text-ink-2">Each code works one time. Store them in your password manager, not in email or chat.</p>
      <ul className="grid grid-cols-1 gap-2 rounded-lg bg-subtle p-3 font-mono text-sm sm:grid-cols-2">{codes.map((c) => <li key={c} className="whitespace-nowrap">{c}</li>)}</ul>
      <button type="button" className="btn btn-ghost w-full" onClick={() => navigator.clipboard?.writeText(codes.join('\n'))}>Copy codes</button>
      <label className="flex items-center gap-3 text-sm"><input type="checkbox" className="size-5" checked={saved} onChange={(e) => setSaved(e.target.checked)} />I have saved these codes</label>
      {saved ? <Link href="/login" className="btn w-full">Go to sign in</Link> : <button className="btn w-full" disabled>Go to sign in</button>}
    </AuthShell>
  )
}
